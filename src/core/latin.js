export const LATIN_H = 9; // 行の数（下にはみ出す部分まで）

// その文字があるか
export function hasLatin(ch) { return Object.prototype.hasOwnProperty.call(G, ch); }

export function latinWidth(ch) { return G[ch][0].length; }

// 文字を (x, y) に描く（y は大文字の上）
export function drawLatin(ctx, ch, x, y) {
  const rows = G[ch];
  for (let r = 0; r < rows.length; r++) {
    const row = rows[r];
    for (let c = 0; c < row.length; c++) if (row[c] === '#') ctx.fillRect(x + c, y + r, 1, 1);
  }
}
